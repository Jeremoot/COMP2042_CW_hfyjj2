package main.java.brickGame;

/**
 * Configurations for the game scene.
 * This class contains static fields that define the dimensions of the game scene.
 */
public class GameConfig {

    /**
     * The width of the game scene.
     * Specifies the horizontal dimension of the game's playing area.
     */
    public static final int sceneWidth = 500;

    /**
     * The height of the game scene.
     * Specifies the vertical dimension of the game's playing area.
     */
    public static final int sceneHeight = 700;
}
